export const normalizeLanguage = (value?: string | null): AppLanguage => {
  const raw = String(value || 'pt-BR').trim()
  const normalized = raw.toLowerCase().replace(/_/g, '-')
  if (
    normalized === 'pt' ||
    normalized === 'pt-br' ||
    normalized.startsWith('pt') ||
    normalized.includes('portuguese') ||
    normalized.includes('portugues')
  ) return 'pt-BR'
  if (
    normalized === 'en' ||
    normalized === 'en-us' ||
    normalized.startsWith('en') ||
    normalized.includes('english')
  ) return 'en-US'
  if (
    normalized === 'es' ||
    normalized === 'es-es' ||
    normalized.startsWith('es') ||
    normalized.includes('spanish') ||
    normalized.includes('espanol')
  ) return 'es-ES'
  if (
    normalized === 'it' ||
    normalized === 'it-it' ||
    normalized.startsWith('it') ||
    normalized.includes('italian') ||
    normalized.includes('italiano')
  ) return 'it-IT'
  return 'pt-BR'
}

export const translate = (
  language: AppLanguage,
  key: string,
  vars?: Record<string, string | number>
): string => {
  const base = dictionaries[language] || dictionaries['pt-BR']
  const fallback = dictionaries['pt-BR']
  const template = base[key] || fallback[key] || key
  if (!vars) return template
  return Object.keys(vars).reduce((acc, varKey) => {
    return acc.replace(new RegExp(`\\{${varKey}\\}`, 'g'), String(vars[varKey]))
  }, template)
}
